import { readFileSync } from 'node:fs';
import { describe, it, expect } from 'vitest';
import { createHmac } from 'node:crypto';
import { signPantryIdentity, verifyPantryIdentity } from '@/lib/pantry-identity';
const secret = 'a-strong-server-secret';
const now = 1_800_000_000_000;
function header(token: string) {
  return `Bearer ${token}`;
}
function altered(changes: Record<string, unknown>) {
  const [raw] = signPantryIdentity('cookbook-user', 'Person@Example.com', secret, now).split('.');
  const data = { ...JSON.parse(Buffer.from(raw!, 'base64url').toString()), ...changes };
  const payload = Buffer.from(JSON.stringify(data)).toString('base64url');
  return header(`${payload}.${createHmac('sha256', secret).update(payload).digest('base64url')}`);
}
describe('signed pantry identities', () => {
  it('normalizes case without merging plus aliases or Gmail dots', () => {
    const token = signPantryIdentity(
      'cookbook-user',
      ' Person.Name+pantry@Example.com ',
      secret,
      now,
    );
    expect(verifyPantryIdentity(header(token), secret, now)?.email).toBe(
      'person.name+pantry@example.com',
    );
  });
  it('checks signature, audience, issuer, version, email, subject and lifetime', () => {
    const token = signPantryIdentity('cookbook-user', 'person@example.com', secret, now);
    expect(verifyPantryIdentity(header(token), 'wrong', now)).toBeNull();
    expect(verifyPantryIdentity(header(token), secret, now + 60_000)).toBeNull();
    expect(verifyPantryIdentity(header(token), secret, now - 30_000)).toBeNull();
    for (const change of [
      { audience: 'other' },
      { issuer: 'other' },
      { version: 1 },
      { subject: '' },
      { email: 'bad' },
      { email: 'Person@example.com' },
      { expiresAt: now / 1000 + 120 },
    ]) {
      expect(verifyPantryIdentity(altered(change), secret, now)).toBeNull();
    }
    expect(verifyPantryIdentity(header(token + 'garbage'), secret, now)).toBeNull();
  });
});

it('accepts the same fixed contract token generated by Cookbook', () => {
  const vector = JSON.parse(
    readFileSync(new URL('../fixtures/pantry-identity-v2.json', import.meta.url), 'utf8'),
  );
  expect(signPantryIdentity(vector.subject, vector.email, vector.secret, vector.now)).toBe(
    vector.token,
  );
  expect(verifyPantryIdentity(`Bearer ${vector.token}`, vector.secret, vector.now)?.subject).toBe(
    vector.subject,
  );
});
